import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../.github/workflows/slop-public.md", import.meta.url);
const target = new URL("../.github/workflows/slop-org.md", import.meta.url);

function replaceOnce(text, before, after) {
  const parts = text.split(before);
  if (parts.length !== 2)
    throw new Error("Unable to derive organisation workflow from source");
  return parts.join(after);
}

let result = await readFile(source, "utf8");
result = replaceOnce(
  result,
  "    secrets:\n      COPILOT_GITHUB_TOKEN:\n        required: true\n",
  "",
);
result = replaceOnce(
  result,
  "  actions: read\nengine:\n",
  "  actions: read\n  copilot-requests: write\nengine:\n",
);
result = replaceOnce(
  result,
  "---\ndescription:",
  "---\n# Generated by scripts/derive-org-workflow.mjs; edit slop-public.md instead.\ndescription:",
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== result)
    throw new Error("Organisation workflow is out of date");
} else {
  await writeFile(target, result);
}
